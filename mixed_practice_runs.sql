-- Run this once in Supabase SQL Editor.
-- The rows are per-user, so one user's generated sequence does not consume
-- questions for another user.

create table if not exists public.mixed_practice_runs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  total_questions integer not null default 0,
  set_size integer not null default 50,
  status text not null default 'active'
    check (status in ('active', 'completed')),
  created_at timestamptz not null default now()
);

create table if not exists public.mixed_practice_run_questions (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.mixed_practice_runs(id) on delete cascade,
  question_id text not null,
  subject text not null,
  set_number integer not null,
  position integer not null,
  strategy text not null
    check (strategy in ('pyq-weighted', 'remaining-inventory')),
  created_at timestamptz not null default now(),
  unique (run_id, question_id),
  unique (run_id, set_number, position)
);

create index if not exists mixed_practice_runs_user_idx
  on public.mixed_practice_runs(user_id, created_at desc);

create index if not exists mixed_practice_run_questions_run_idx
  on public.mixed_practice_run_questions(run_id, set_number, position);

alter table public.mixed_practice_runs enable row level security;
alter table public.mixed_practice_run_questions enable row level security;

drop policy if exists "Users can read their mixed practice runs"
on public.mixed_practice_runs;
create policy "Users can read their mixed practice runs"
on public.mixed_practice_runs
for select
using (auth.uid() = user_id);

drop policy if exists "Users can create their mixed practice runs"
on public.mixed_practice_runs;
create policy "Users can create their mixed practice runs"
on public.mixed_practice_runs
for insert
with check (auth.uid() = user_id);

drop policy if exists "Users can update their mixed practice runs"
on public.mixed_practice_runs;
create policy "Users can update their mixed practice runs"
on public.mixed_practice_runs
for update
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can delete their mixed practice runs"
on public.mixed_practice_runs;
create policy "Users can delete their mixed practice runs"
on public.mixed_practice_runs
for delete
using (auth.uid() = user_id);

drop policy if exists "Users can read their mixed practice run questions"
on public.mixed_practice_run_questions;
create policy "Users can read their mixed practice run questions"
on public.mixed_practice_run_questions
for select
using (
  exists (
    select 1
    from public.mixed_practice_runs r
    where r.id = run_id
      and r.user_id = auth.uid()
  )
);

drop policy if exists "Users can create their mixed practice run questions"
on public.mixed_practice_run_questions;
create policy "Users can create their mixed practice run questions"
on public.mixed_practice_run_questions
for insert
with check (
  exists (
    select 1
    from public.mixed_practice_runs r
    where r.id = run_id
      and r.user_id = auth.uid()
  )
);

drop policy if exists "Users can delete their mixed practice run questions"
on public.mixed_practice_run_questions;
create policy "Users can delete their mixed practice run questions"
on public.mixed_practice_run_questions
for delete
using (
  exists (
    select 1
    from public.mixed_practice_runs r
    where r.id = run_id
      and r.user_id = auth.uid()
  )
);
